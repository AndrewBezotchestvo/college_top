#for - цикл, перебирающий какие либо значения

#перебор отдельных значений
for i in 1, 2, 3, 4, 5, "a", "b":
     print(i)

#перебор элементов с range
#range - генератор чисел
#range(a, b, c) от a до b и с шагом с
#range(a) от 0 до a c шагом 1
#range(a, b) от a до b и c шагом 1
for i in range(100):
    print(i)
    
for i in "привет", "мир":
    print(i)
    

